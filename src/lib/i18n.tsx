const dicts: Record<Lang, Dict> = { fr, ar, en };

export const languages: { code: Lang; label: string; native: string; flag: string }[] = [
  { code: "fr", label: "French", native: "Français", flag: "🇫🇷" },
  { code: "ar", label: "Arabic", native: "العربية", flag: "🇲🇦" },
  { code: "en", label: "English", native: "English", flag: "🇬🇧" },
];

type TFn = (key: string, vars?: Record<string, string | number>) => string;
type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: TFn; dir: "ltr" | "rtl" };
const I18nCtx = createContext<Ctx | null>(null);

function makeT(lang: Lang): TFn {
  return (key, vars) => {
    let s = dicts[lang][key] ?? dicts.fr[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.replaceAll(`{${k}}`, String(vars[k]));
    return s;
  };
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");

  useEffect(() => {
    try {
      const stored = localStorage.getItem("clinicab.lang") as Lang | null;
      if (stored && dicts[stored]) setLangState(stored);
    } catch {}
  }, []);

  const dir: "ltr" | "rtl" = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem("clinicab.lang", l); } catch {}
  };

  const value = useMemo<Ctx>(() => ({ lang, setLang, dir, t: makeT(lang) }), [lang, dir]);

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nCtx);
  if (!ctx) return { lang: "fr" as Lang, setLang: () => {}, dir: "ltr" as const, t: makeT("fr") };
  return ctx;
}

export function useT() {
  return useI18n().t;
}
